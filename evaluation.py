"""Gemini-assisted evaluation helpers for the RAG notebook."""

from __future__ import annotations

import json
import time
from pathlib import Path

import pandas as pd

from documents import build_header


def generate_ground_truth(
    documents: pd.DataFrame,
    client,
    model: str,
    cache_path: Path,
    force: bool = False,
    n: int = 15,
    request_delay: int = 13,
    random_state: int = 42,
) -> list[dict]:
    """Create or load a small, reproducible source-grounded test set."""
    if cache_path.exists() and not force:
        with cache_path.open(encoding="utf-8") as handle:
            return json.load(handle)
    if client is None:
        return []

    candidates = documents[documents["text"].str.len() > 1000]
    sample = candidates.sample(n=min(n, len(candidates)), random_state=random_state)
    test_set = []

    for _, document in sample.iterrows():
        prompt = (
            "Based on the following source passage, generate one complex question and its "
            "correct answer. Return JSON with keys 'question' and 'answer'.\n\n"
            f"SOURCE PASSAGE:\n{build_header(document)}\n\nBody:\n{document['text']}"
        )
        try:
            response = client.models.generate_content(model=model, contents=prompt)
            item = _parse_json_response(response.text)
            item["source_ids"] = document["source_ids"]
            test_set.append(item)
            time.sleep(request_delay)
        except Exception as error:
            print(f"Gemini API error: {error}")

    if test_set:
        with cache_path.open("w", encoding="utf-8") as handle:
            json.dump(test_set, handle, ensure_ascii=False)
    return test_set


def evaluate_system(
    test_set: list[dict],
    answer_question,
    client,
    model: str,
    cache_path: Path,
    force: bool = False,
    request_delay: int = 13,
) -> list[dict]:
    """Ask Gemini to judge source-grounded answers generated by the local RAG system."""
    if cache_path.exists() and not force:
        with cache_path.open(encoding="utf-8") as handle:
            return json.load(handle)
    if client is None:
        return []

    results = []
    for item in test_set:
        rag_answer = answer_question(item["question"])
        judge_prompt = f"""You are an expert judge evaluating a RAG system.
Compare the System Answer against the Gold Answer for the Question.

Question: {item['question']}
Gold Answer: {item['answer']}
System Answer: {rag_answer}
Expected Source Document IDs: {item.get('source_ids', [])}

Score from 1 to 10 based on accuracy, faithfulness, and citations.
Return only JSON with keys 'score' (int) and 'reasoning' (string)."""
        try:
            response = client.models.generate_content(model=model, contents=judge_prompt)
            judgment = _parse_json_response(response.text)
            results.append(
                {
                    "question": item["question"],
                    "gold": item["answer"],
                    "source_ids": item.get("source_ids", []),
                    "rag": rag_answer,
                    "score": judgment["score"],
                    "reasoning": judgment["reasoning"],
                }
            )
            time.sleep(request_delay)
        except Exception as error:
            print(f"Evaluation error: {error}")

    if results:
        with cache_path.open("w", encoding="utf-8") as handle:
            json.dump(results, handle, ensure_ascii=False)
    return results


def _parse_json_response(text: str) -> dict:
    return json.loads(text.strip().removeprefix("```json").removesuffix("```").strip())
